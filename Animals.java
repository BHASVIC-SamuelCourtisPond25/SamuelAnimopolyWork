public class Animals {
    int price;
    int level;
    int rent;
    boolean animal_owned = false;
    int animal_owner;

    Animals(int pPrice, int pLevel, int pRent, boolean pAnimal_owned, int pAnimal_owner){
        price = pPrice;
        level = pLevel;
        rent = pRent;
        animal_owned = pAnimal_owned;
        animal_owner = pAnimal_owner;

    }
}
